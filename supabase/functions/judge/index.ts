// CrossPhrase judge: grades each across/down phrase with Claude Haiku.
//
// POST { entries: [{ id: "1A", words: ["the", "golden", "toast"] }, ...] }
//  ->  { verdicts: [{ entryId, valid, tier, reading, reason, quip }, ...] }
//
// Callers must be signed in (the app signs players in anonymously). Phrases
// are answered from the shared verdict cache where possible, each player is
// rate limited, and every request is logged to judge_calls for cost tracking.
//
// Deploy:  supabase functions deploy judge
// Secret:  supabase secrets set ANTHROPIC_API_KEY=sk-ant-...

import { type SupabaseContext, withSupabase } from "npm:@supabase/server@1.9.2";
import dictionary from "../_shared/dictionary.json" with { type: "json" };
import { type CachedVerdict, type JudgeDeps, judgeEntries, parseEntries } from "./judge.ts";
import { Anthropic, callModel, MODEL, PROMPT_VERSION } from "./model.ts";

/** word -> parts of speech, generated by scripts/build_words.py. */
const DICTIONARY = new Map<string, string[]>(Object.entries(dictionary));

const envInt = (name: string, fallback: number) => Number(Deno.env.get(name) ?? fallback);

/** Requests allowed per player per window. A level takes at most 3 submits. */
const LIMITS = [
  { windowSeconds: 10 * 60, limit: envInt("JUDGE_LIMIT_PER_10_MIN", 40) },
  { windowSeconds: 24 * 60 * 60, limit: envInt("JUDGE_LIMIT_PER_DAY", 400) },
];

type AdminClient = SupabaseContext["supabaseAdmin"];

function cacheDeps(admin: AdminClient): JudgeDeps {
  return {
    dictionary: DICTIONARY,
    promptVersion: PROMPT_VERSION,
    async lookup(phrases) {
      const { data, error } = await admin
        .from("verdict_cache")
        .select("phrase, tier, reading, reason, quip, prompt_version, source")
        .in("phrase", phrases);
      if (error) throw error;
      return data as CachedVerdict[];
    },
    async save(rows) {
      if (rows.length === 0) return;
      const { error } = await admin
        .from("verdict_cache")
        .upsert(rows.map((r) => ({ ...r, updated_at: new Date().toISOString() })));
      if (error) throw error;
    },
    async recordHits(phrases) {
      const { error } = await admin.rpc("record_verdict_hits", { p_phrases: phrases });
      if (error) throw error;
    },
    callModel,
  };
}

export default {
  fetch: withSupabase({ auth: "user" }, async (req, ctx) => {
    if (req.method !== "POST") return Response.json({ error: "POST only" }, { status: 405 });
    const userId = ctx.userClaims?.id;
    if (!userId) return Response.json({ error: "sign in first" }, { status: 401 });

    let body: unknown;
    try {
      body = await req.json();
    } catch {
      return Response.json({ error: "body must be JSON" }, { status: 400 });
    }
    const entries = parseEntries(body, DICTIONARY);
    if (typeof entries === "string") return Response.json({ error: entries }, { status: 400 });

    const admin = ctx.supabaseAdmin;
    for (const { windowSeconds, limit } of LIMITS) {
      const { data: allowed, error } = await admin.rpc("consume_judge_quota", {
        p_user: userId,
        p_window_seconds: windowSeconds,
        p_limit: limit,
      });
      if (error) {
        console.error("quota check failed", error);
        return Response.json({ error: "judge unavailable" }, { status: 503 });
      }
      if (!allowed) return Response.json({ error: "too many requests" }, { status: 429 });
    }

    const started = Date.now();
    try {
      const result = await judgeEntries(entries, cacheDeps(admin));
      const { error } = await admin.from("judge_calls").insert({
        user_id: userId,
        phrases: entries.length,
        cache_hits: result.cacheHits,
        model: result.usage ? MODEL : null,
        input_tokens: result.usage?.inputTokens ?? 0,
        output_tokens: result.usage?.outputTokens ?? 0,
        cache_read_tokens: result.usage?.cacheReadTokens ?? 0,
        cache_write_tokens: result.usage?.cacheWriteTokens ?? 0,
        latency_ms: Date.now() - started,
      });
      if (error) console.error("usage log failed", error);
      return Response.json({ verdicts: result.verdicts });
    } catch (error) {
      console.error("judge failed", error);
      // The app grades provisionally offline on any of these and retries later.
      if (error instanceof Anthropic.RateLimitError) {
        return Response.json({ error: "judge is busy" }, { status: 503 });
      }
      return Response.json({ error: "judge failed" }, { status: 502 });
    }
  }),
};
