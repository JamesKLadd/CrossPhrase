// Bundles the leaderboard server's scoring (src/server/scores.ts, with the
// shared game core, word data, built-in judge, levels and daily puzzles) into
// one ES module the Supabase `scores` function imports. Rebuild it whenever
// any of those change; `npm test` fails while it's out of date.
//
//   npm run bundle:server            rebuild
//   node scripts/bundle-server.mjs --check   exit 1 if the committed bundle is stale

import { build } from 'esbuild';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const OUT = new URL('../supabase/functions/_shared/scores.bundle.js', import.meta.url);

async function bundleServer() {
  const result = await build({
    entryPoints: [new URL('../src/server/scores.ts', import.meta.url).pathname],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    write: false,
    legalComments: 'none',
    banner: { js: '// Generated by scripts/bundle-server.mjs from src/server/scores.ts. Do not edit.' },
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

const code = await bundleServer();
if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== code) {
    console.error('supabase/functions/_shared/scores.bundle.js is out of date: run npm run bundle:server');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, code);
  console.log(`Wrote supabase/functions/_shared/scores.bundle.js (${Math.round(code.length / 1024)} KB).`);
}
